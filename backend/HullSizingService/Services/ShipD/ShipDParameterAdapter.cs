                _logger.LogInformation("[SHIPD_ADAPTER] ✅ Applied data-driven barge_type defaults: Rc={Rc}, Rk={Rk}",
                    vector[9], vector[10]);
                break;

            case "deep_v":
                // Data-driven values for planning hull deadrise
