using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using HullSizingService.Services.Integration;
using Shared.DTOs.ShipD;
using Shared.DTOs.Sizing;
using Shared.Models.Sizing;

namespace HullSizingService.Services.ShipD;

/// <summary>
/// Temporary adapter that maps mission cases to ShipD parameter vectors.
/// This implementation uses placeholder logic until full ShipD metadata ingestion is completed.
/// </summary>
public class ShipDParameterAdapter : IShipDParameterAdapter
{
    private const int ShipDParameterCount = 45;

    private readonly ILogger<ShipDParameterAdapter> _logger;
    private readonly IDataServiceClient _dataServiceClient;

    public ShipDParameterAdapter(
        ILogger<ShipDParameterAdapter> logger,
        IDataServiceClient dataServiceClient)
    {
        _logger = logger;
        _dataServiceClient = dataServiceClient;
    }

    public async Task<ShipDParameterizationResult> BuildAsync(
        MissionCase missionCase,
        CreateSizingRunDto runRequest,
        CancellationToken cancellationToken = default)
    {
        // Fetch metadata (best-effort; fall back to local defaults if unavailable)
        var parameterMetadataTask = _dataServiceClient.GetShipDParameterMetadataAsync(cancellationToken);
        var taxonomyTask = _dataServiceClient.GetShipDVesselTaxonomyAsync(cancellationToken);
        await Task.WhenAll(parameterMetadataTask, taxonomyTask);

        var parameterMetadata = parameterMetadataTask.Result;
        var taxonomy = taxonomyTask.Result;

        // Use incoming selections when available; otherwise fall back to mission defaults.
        var vesselCategory = (runRequest.VesselCategory ?? missionCase.MissionCategory ?? "commercial").ToLowerInvariant();
        var vesselType = (runRequest.VesselType ?? missionCase.MissionType).ToLowerInvariant();
        var bowFamily = runRequest.BowFamily ?? missionCase.BowFamily;
        var midshipFamily = runRequest.MidshipFamily ?? missionCase.MidshipFamily;
        var sternFamily = runRequest.SternFamily ?? missionCase.SternFamily;
        var maskVersion = runRequest.FamilyMaskVersion ?? missionCase.FamilyMaskVersion ?? 1;

        var taxonomyEntry = taxonomy.FirstOrDefault(t =>
            string.Equals(t.Category, vesselCategory, StringComparison.OrdinalIgnoreCase) &&
            string.Equals(t.Type, vesselType, StringComparison.OrdinalIgnoreCase));

        // Placeholder vector: start with zeros and inject a few normalized mission hints.
        var vector = Enumerable.Repeat(0m, ShipDParameterCount).ToArray();
        var warnings = new List<string>();

        if (!string.IsNullOrWhiteSpace(runRequest.ShipdInputVectorJson))
        {
            try
            {
                var overrideVector = JsonSerializer.Deserialize<List<decimal>>(runRequest.ShipdInputVectorJson);
                if (overrideVector != null && overrideVector.Count == ShipDParameterCount)
                {
                    vector = overrideVector.ToArray();
                }
                else
                {
                    warnings.Add("Provided ShipD input vector did not contain 45 entries; using autogenerated defaults.");
                }
            }
            catch (JsonException ex)
            {
                warnings.Add("Provided ShipD input vector could not be parsed; using autogenerated defaults.");
                _logger.LogWarning(ex, "[SHIPD_ADAPTER] Failed to parse user-supplied ShipD vector. Falling back to autogenerated defaults.");
            }
        }
        if (missionCase.CapLoaM.HasValue && missionCase.CapLoaM.Value > 0)
        {
            vector[0] = Math.Clamp(missionCase.CapLoaM.Value / 300m, 0.0m, 1.0m);
        }

        if (missionCase.CapBeamM.HasValue && missionCase.CapBeamM.Value > 0)
        {
            vector[7] = Math.Clamp(missionCase.CapBeamM.Value / 50m, 0.0m, 1.0m);
        }

        if (missionCase.ServiceSpeedKn > 0)
        {
            vector[20] = Math.Clamp(missionCase.ServiceSpeedKn / 40m, 0.0m, 1.0m);
        }

        // Extract additionalParameters from MissionCase.ShipdInputsJson as fallback if not in request
        // This must happen BEFORE applying taxonomy defaults so user values can override defaults
        IDictionary<string, object>? effectiveAdditionalParameters = runRequest.Options?.AdditionalParameters;
        if ((effectiveAdditionalParameters == null || effectiveAdditionalParameters.Count == 0) &&
            !string.IsNullOrWhiteSpace(missionCase.ShipdInputsJson))
        {
            try
            {
                var shipdInputs = JsonSerializer.Deserialize<Dictionary<string, object>>(missionCase.ShipdInputsJson);
                if (shipdInputs != null && shipdInputs.TryGetValue("additionalParameters", out var additionalParamsObj))
                {
                    if (additionalParamsObj is JsonElement jsonElement)
                    {
                        effectiveAdditionalParameters = JsonSerializer.Deserialize<Dictionary<string, object>>(jsonElement.GetRawText());
                    }
                    else if (additionalParamsObj is Dictionary<string, object> dict)
                    {
                        effectiveAdditionalParameters = dict;
                    }
                    else
                    {
                        var json = JsonSerializer.Serialize(additionalParamsObj);
                        effectiveAdditionalParameters = JsonSerializer.Deserialize<Dictionary<string, object>>(json);
                    }

                    if (effectiveAdditionalParameters != null && effectiveAdditionalParameters.Count > 0)
                    {
                        _logger.LogDebug("[SHIPD_ADAPTER] Extracted {Count} additional parameters from MissionCase.ShipdInputsJson as fallback",
                            effectiveAdditionalParameters.Count);
                    }
                }
            }
            catch (JsonException ex)
            {
                _logger.LogWarning(ex, "[SHIPD_ADAPTER] Failed to extract additionalParameters from MissionCase.ShipdInputsJson as fallback");
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "[SHIPD_ADAPTER] Unexpected error extracting additionalParameters from MissionCase.ShipdInputsJson");
            }
        }

        // Extract bow/stern length ratio defaults from taxonomy
        decimal? defaultBow = null;
        decimal? defaultStern = null;
        if (taxonomyEntry != null && !string.IsNullOrWhiteSpace(taxonomyEntry.AdditionalParametersJson))
        {
            try
            {
                var taxonomyParams = JsonSerializer.Deserialize<Dictionary<string, object>>(taxonomyEntry.AdditionalParametersJson);
                if (taxonomyParams != null)
                {
                    if (taxonomyParams.TryGetValue("bowLengthRatio", out var bowObj) && bowObj != null)
                    {
                        defaultBow = ExtractDecimalValue(bowObj);
                        _logger.LogDebug("[SHIPD_ADAPTER] Extracted taxonomy default bow length ratio: {Ratio}", defaultBow);
                    }
                    if (taxonomyParams.TryGetValue("sternLengthRatio", out var sternObj) && sternObj != null)
                    {
                        defaultStern = ExtractDecimalValue(sternObj);
                        _logger.LogDebug("[SHIPD_ADAPTER] Extracted taxonomy default stern length ratio: {Ratio}", defaultStern);
                    }
                }
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "[SHIPD_ADAPTER] Failed to parse bow/stern defaults from taxonomy AdditionalParametersJson");
            }
        }
        else if (taxonomyEntry == null)
        {
            _logger.LogWarning("[SHIPD_ADAPTER] No taxonomy entry found for category '{Category}' and type '{Type}' - cannot extract bow/stern defaults", vesselCategory, vesselType);
        }
        else
        {
            _logger.LogWarning("[SHIPD_ADAPTER] Taxonomy entry found but AdditionalParametersJson is empty - cannot extract bow/stern defaults");
        }

        // Apply taxonomy defaults when available
        if (taxonomyEntry != null)
        {
            if (bowFamily == null && taxonomyEntry.BowFamilies.Count > 0)
            {
                bowFamily = taxonomyEntry.BowFamilies.First();
                warnings.Add($"Bow family defaulted to '{bowFamily}' from taxonomy.");
            }

            if (midshipFamily == null && taxonomyEntry.MidshipFamilies.Count > 0)
            {
                midshipFamily = taxonomyEntry.MidshipFamilies.First();
                warnings.Add($"Midship family defaulted to '{midshipFamily}' from taxonomy.");
            }

            if (sternFamily == null && taxonomyEntry.SternFamilies.Count > 0)
            {
                sternFamily = taxonomyEntry.SternFamilies.First();
                warnings.Add($"Stern family defaulted to '{sternFamily}' from taxonomy.");
            }
        }
        else
        {
            warnings.Add($"No taxonomy entry found for category '{vesselCategory}' and type '{vesselType}'.");
        }

        if (bowFamily is null || midshipFamily is null || sternFamily is null)
        {
            warnings.Add("One or more hull families were not specified; using defaults during ShipD processing.");
        }

        // Apply taxonomy defaults for bow/stern length ratios if not provided by user
        // This must happen before ApplyConditionalParameters so user overrides can take precedence
        ShipDAdditionalParameters? additionalParsed = null;
        bool hasUserBowRatio = false;
        bool hasUserSternRatio = false;

        if (effectiveAdditionalParameters != null && effectiveAdditionalParameters.Count > 0)
        {
            try
            {
                var json = JsonSerializer.Serialize(effectiveAdditionalParameters);
                var options = new JsonSerializerOptions
                {
                    PropertyNameCaseInsensitive = true,
                    PropertyNamingPolicy = JsonNamingPolicy.CamelCase
                };
                additionalParsed = JsonSerializer.Deserialize<ShipDAdditionalParameters>(json, options);
                hasUserBowRatio = additionalParsed?.BowLengthRatio.HasValue == true;
                hasUserSternRatio = additionalParsed?.SternLengthRatio.HasValue == true;
                _logger.LogDebug("[SHIPD_ADAPTER] Parsed AdditionalParameters for defaults check. BowLengthRatio: {Bow}, SternLengthRatio: {Stern}, HasUserBow: {HasBow}, HasUserStern: {HasStern}",
                    additionalParsed?.BowLengthRatio, additionalParsed?.SternLengthRatio, hasUserBowRatio, hasUserSternRatio);
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "[SHIPD_ADAPTER] Failed to parse AdditionalParameters for defaults check. Will try in ApplyConditionalParameters.");
            }
        }

        // Apply taxonomy defaults if user hasn't provided values
        // Check both additionalParsed and vector[1]/vector[2] to ensure we don't override existing values
        if (defaultBow.HasValue && !hasUserBowRatio && vector[1] == 0m)
        {
            vector[1] = defaultBow.Value;
            _logger.LogInformation("[SHIPD_ADAPTER] ✅ Applied taxonomy default bow length ratio: {Ratio} to vector[1]", defaultBow.Value);
        }
        else if (defaultBow.HasValue && hasUserBowRatio)
        {
            _logger.LogDebug("[SHIPD_ADAPTER] Skipped taxonomy default bow length ratio (user provided: {UserValue})", additionalParsed?.BowLengthRatio);
        }
        else if (defaultBow.HasValue && vector[1] != 0m)
        {
            _logger.LogDebug("[SHIPD_ADAPTER] Skipped taxonomy default bow length ratio (vector[1] already set: {Value})", vector[1]);
        }
        else if (!defaultBow.HasValue)
        {
            _logger.LogWarning("[SHIPD_ADAPTER] ⚠️ No taxonomy default for bow length ratio available");
        }

        if (defaultStern.HasValue && !hasUserSternRatio && vector[2] == 0m)
        {
            vector[2] = defaultStern.Value;
            _logger.LogInformation("[SHIPD_ADAPTER] ✅ Applied taxonomy default stern length ratio: {Ratio} to vector[2]", defaultStern.Value);
        }
        else if (defaultStern.HasValue && hasUserSternRatio)
        {
            _logger.LogDebug("[SHIPD_ADAPTER] Skipped taxonomy default stern length ratio (user provided: {UserValue})", additionalParsed?.SternLengthRatio);
        }
        else if (defaultStern.HasValue && vector[2] != 0m)
        {
            _logger.LogDebug("[SHIPD_ADAPTER] Skipped taxonomy default stern length ratio (vector[2] already set: {Value})", vector[2]);
        }
        else if (!defaultStern.HasValue)
        {
            _logger.LogWarning("[SHIPD_ADAPTER] ⚠️ No taxonomy default for stern length ratio available");
        }

        // Apply family-specific defaults from taxonomy (e.g., bit_BB for bulbous_bow, Atrans for transom_stern)
        if (taxonomyEntry != null && !string.IsNullOrWhiteSpace(taxonomyEntry.AdditionalParametersJson))
        {
            try
            {
                var taxonomyParams = JsonSerializer.Deserialize<Dictionary<string, object>>(taxonomyEntry.AdditionalParametersJson);
                if (taxonomyParams != null && taxonomyParams.TryGetValue("familyDefaults", out var familyDefaultsObj))
                {
                    Dictionary<string, Dictionary<string, object>>? familyDefaults = null;
                    if (familyDefaultsObj is JsonElement jsonElement)
                    {
                        familyDefaults = JsonSerializer.Deserialize<Dictionary<string, Dictionary<string, object>>>(jsonElement.GetRawText());
                    }
                    else if (familyDefaultsObj is Dictionary<string, Dictionary<string, object>> dict)
                    {
                        familyDefaults = dict;
                    }

                    if (familyDefaults != null)
                    {
                        // Apply bow family defaults
                        if (!string.IsNullOrEmpty(bowFamily) && familyDefaults.TryGetValue(bowFamily, out var bowDefaults))
                        {
                            ApplyFamilyDefaults(vector, bowDefaults, "bow", bowFamily, parameterMetadata, warnings);
                        }

                        // Apply midship family defaults
                        if (!string.IsNullOrEmpty(midshipFamily) && familyDefaults.TryGetValue(midshipFamily, out var midDefaults))
                        {
                            ApplyFamilyDefaults(vector, midDefaults, "midship", midshipFamily, parameterMetadata, warnings);
                        }

                        // Apply stern family defaults
                        if (!string.IsNullOrEmpty(sternFamily) && familyDefaults.TryGetValue(sternFamily, out var sternDefaults))
                        {
                            ApplyFamilyDefaults(vector, sternDefaults, "stern", sternFamily, parameterMetadata, warnings);
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "[SHIPD_ADAPTER] Failed to apply family-specific defaults from taxonomy");
            }
        }

        // CRITICAL FIX: Apply hardcoded family defaults if taxonomy doesn't provide them
        // This ensures different family selections always produce visually distinct hull shapes
        _logger.LogInformation("[SHIPD_ADAPTER] Applying hardcoded family defaults as fallback: bow={Bow}, midship={Mid}, stern={Stern}",
            bowFamily ?? "none", midshipFamily ?? "none", sternFamily ?? "none");
        ApplyHardcodedBowFamilyDefaults(vector, bowFamily, parameterMetadata);
        ApplyHardcodedSternFamilyDefaults(vector, sternFamily, parameterMetadata);
        ApplyHardcodedMidshipFamilyDefaults(vector, midshipFamily, parameterMetadata);

        // Apply conditional parameters from AdditionalParameters (using effectiveAdditionalParameters)
        ApplyConditionalParameters(
            vector,
            effectiveAdditionalParameters,
            bowFamily,
            midshipFamily,
            sternFamily,
            parameterMetadata,
            warnings);

        IDictionary<string, object>? additional = effectiveAdditionalParameters;

        if (!string.IsNullOrWhiteSpace(taxonomyEntry?.AdditionalParametersJson))
        {
            try
            {
                var taxonomyParams = JsonSerializer.Deserialize<Dictionary<string, object>>(taxonomyEntry.AdditionalParametersJson);
                if (taxonomyParams != null)
                {
                    additional ??= new Dictionary<string, object>();
                    foreach (var pair in taxonomyParams)
                    {
                        additional[pair.Key] = pair.Value;
                    }
                }
            }
            catch (JsonException ex)
            {
                warnings.Add("Failed to parse additional taxonomy parameters.");
                _logger.LogWarning(ex, "[SHIPD_ADAPTER] Could not parse AdditionalParametersJson for taxonomy entry {Category}/{Type}", vesselCategory, vesselType);
            }
        }

        var labels = parameterMetadata.Count == ShipDParameterCount
            ? parameterMetadata
                .OrderBy(p => p.ParameterIndex)
                .Select(p => p.Label)
                .ToArray()
            : Enumerable.Range(0, ShipDParameterCount)
                .Select(i => $"param_{i:00}")
                .ToArray();

        _logger.LogDebug(
            "[SHIPD_ADAPTER] Generated ShipD vector (maskVersion={MaskVersion}) for category={Category}, type={Type}, bow={Bow}, mid={Mid}, stern={Stern}. Payload={Payload}",
            maskVersion,
            vesselCategory,
            vesselType,
            bowFamily,
            midshipFamily,
            sternFamily,
            JsonSerializer.Serialize(vector));

        var result = new ShipDParameterizationResult(
            ParameterVector: vector,
            ParameterLabels: labels,
            VesselCategory: vesselCategory,
            VesselType: vesselType,
            BowFamily: bowFamily,
            MidshipFamily: midshipFamily,
            SternFamily: sternFamily,
            MaskVersion: maskVersion,
            AdditionalParameters: additional,
            Warnings: warnings);

        return result;
    }

    /// <summary>
    /// Applies conditional parameters from AdditionalParameters to the ShipD vector.
    /// Maps user inputs to ShipD parameter indices based on selected families.
    /// </summary>
    private void ApplyConditionalParameters(
        decimal[] vector,
        IDictionary<string, object>? additionalParameters,
        string? bowFamily,
        string? midshipFamily,
        string? sternFamily,
        IReadOnlyList<ShipDParameterMetadataDto> metadata,
        List<string> warnings)
    {
        if (additionalParameters == null || additionalParameters.Count == 0)
        {
            return;
        }

        // Try to deserialize as ShipDAdditionalParameters
        // Use camelCase naming policy to match frontend JSON
        ShipDAdditionalParameters? additional = null;
        try
        {
            var json = JsonSerializer.Serialize(additionalParameters);
            var options = new JsonSerializerOptions
            {
                PropertyNameCaseInsensitive = true,
                PropertyNamingPolicy = JsonNamingPolicy.CamelCase
            };
            additional = JsonSerializer.Deserialize<ShipDAdditionalParameters>(json, options);
            _logger.LogDebug("[SHIPD_ADAPTER] Successfully deserialized AdditionalParameters. BowLengthRatio: {Bow}, SternLengthRatio: {Stern}",
                additional?.BowLengthRatio, additional?.SternLengthRatio);
        }
        catch (JsonException ex)
        {
            _logger.LogWarning(ex, "[SHIPD_ADAPTER] Failed to deserialize AdditionalParameters as ShipDAdditionalParameters. Attempting manual mapping.");
        }

        if (additional == null)
        {
            // Fallback: try manual mapping from dictionary
            ApplyConditionalParametersFromDictionary(vector, additionalParameters, bowFamily, midshipFamily, sternFamily, metadata, warnings);
            return;
        }

        // Section Geometry (Image 1)
        if (additional.FlareAngleDeg.HasValue)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == 8); // Beta
            if (param != null)
            {
                vector[8] = NormalizeValue(additional.FlareAngleDeg.Value, param.Min, param.Max, param.Mean, param.StdDev);
                _logger.LogDebug("[SHIPD_ADAPTER] Applied flare angle: {Flare}° (normalized: {Normalized})", additional.FlareAngleDeg.Value, vector[8]);
            }
        }

        if (additional.DeadriseAngleDeg.HasValue)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == 19); // Cdrft
            if (param != null)
            {
                vector[19] = NormalizeValue(additional.DeadriseAngleDeg.Value, param.Min, param.Max, param.Mean, param.StdDev);
                _logger.LogDebug("[SHIPD_ADAPTER] Applied deadrise angle: {Deadrise}° (normalized: {Normalized})", additional.DeadriseAngleDeg.Value, vector[19]);
            }
        }

        // Chine type affects Rc (index 9) and Rk (index 10)
        if (!string.IsNullOrEmpty(additional.ChineType))
        {
            if (additional.ChineType.Equals("hard", StringComparison.OrdinalIgnoreCase))
            {
                // Hard chine: sharper transition, lower Rc, higher Rk
                vector[9] = 0.2m;  // Lower curvature
                vector[10] = 0.8m; // Higher knuckle
                _logger.LogDebug("[SHIPD_ADAPTER] Applied hard chine: Rc=0.2, Rk=0.8");
            }
            else if (additional.ChineType.Equals("soft", StringComparison.OrdinalIgnoreCase))
            {
                // Soft chine: rounded transition, higher Rc, lower Rk
                vector[9] = 0.6m;  // Higher curvature
                vector[10] = 0.3m; // Lower knuckle
                _logger.LogDebug("[SHIPD_ADAPTER] Applied soft chine: Rc=0.6, Rk=0.3");
            }
        }

        // Tumblehome toggle (bit_EP_T, index 21)
        if (additional.TumblehomeEnabled == true && midshipFamily == "fine_midship")
        {
            vector[21] = 1.0m;
            _logger.LogDebug("[SHIPD_ADAPTER] Enabled tumblehome for fine_midship");
        }

        // Longitudinal Segmentation (Image 2)
        if (additional.BowLengthRatio.HasValue)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == 1); // Lb
            if (param != null)
            {
                vector[1] = Math.Clamp(additional.BowLengthRatio.Value, param.Min ?? 0m, param.Max ?? 1m);
                _logger.LogDebug("[SHIPD_ADAPTER] Applied bow length ratio: {Ratio} (clamped to metadata bounds)", vector[1]);
            }
            else
            {
                // Apply value even if metadata lookup fails (with basic validation)
                vector[1] = Math.Clamp(additional.BowLengthRatio.Value, 0.05m, 0.9m);
                _logger.LogWarning("[SHIPD_ADAPTER] Applied bow length ratio: {Ratio} (metadata lookup failed, using basic bounds)", vector[1]);
            }
        }

        if (additional.SternLengthRatio.HasValue)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == 2); // Ls
            if (param != null)
            {
                vector[2] = Math.Clamp(additional.SternLengthRatio.Value, param.Min ?? 0m, param.Max ?? 1m);
                _logger.LogDebug("[SHIPD_ADAPTER] Applied stern length ratio: {Ratio} (clamped to metadata bounds)", vector[2]);
            }
            else
            {
                // Apply value even if metadata lookup fails (with basic validation)
                vector[2] = Math.Clamp(additional.SternLengthRatio.Value, 0.05m, 0.9m);
                _logger.LogWarning("[SHIPD_ADAPTER] Applied stern length ratio: {Ratio} (metadata lookup failed, using basic bounds)", vector[2]);
            }
        }

        // Validate Lb + Ls < 1.0 (to ensure Lm > 0)
        if (vector[1] + vector[2] >= 1.0m)
        {
            var excess = vector[1] + vector[2] - 0.99m;
            vector[1] = Math.Max(0.05m, vector[1] - excess / 2);
            vector[2] = Math.Max(0.05m, vector[2] - excess / 2);
            warnings.Add($"Adjusted Lb and Ls to ensure Lm > 0 (Lb={vector[1]:F3}, Ls={vector[2]:F3})");
        }

        if (additional.BowRakeAngleDeg.HasValue)
        {
            // Bow rake uses same Beta parameter (index 8) as flare
            // If flare is already set, use the average or prefer rake
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == 8);
            if (param != null)
            {
                if (vector[8] == 0m || !additional.FlareAngleDeg.HasValue)
                {
                    vector[8] = NormalizeValue(additional.BowRakeAngleDeg.Value, param.Min, param.Max, param.Mean, param.StdDev);
                }
                else
                {
                    // Both flare and rake specified - use average
                    var flareNorm = NormalizeValue(additional.FlareAngleDeg.Value, param.Min, param.Max, param.Mean, param.StdDev);
                    var rakeNorm = NormalizeValue(additional.BowRakeAngleDeg.Value, param.Min, param.Max, param.Mean, param.StdDev);
                    vector[8] = (flareNorm + rakeNorm) / 2m;
                }
            }
        }

        if (additional.SternRakeAngleDeg.HasValue)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == 27); // Beta_trans
            if (param != null)
            {
                vector[27] = NormalizeValue(additional.SternRakeAngleDeg.Value, param.Min, param.Max, param.Mean, param.StdDev);
                _logger.LogDebug("[SHIPD_ADAPTER] Applied stern rake angle: {Rake}° (normalized: {Normalized})", additional.SternRakeAngleDeg.Value, vector[27]);
            }
        }

        // Bulb Geometry (Image 3) - only if bulbous_bow or bulbous selected
        // Handle both "bulbous" and "bulbous_bow" family names
        if (bowFamily == "bulbous_bow" || bowFamily == "bulbous")
        {
            // Enable bulb (only if not already set by family defaults)
            if (vector[31] == 0m)
            {
                vector[31] = 1.0m; // bit_BB
            }

            if (additional.BulbLengthRatio.HasValue)
            {
                var param = metadata.FirstOrDefault(m => m.ParameterIndex == 33); // Lbb
                if (param != null)
                {
                    vector[33] = Math.Clamp(additional.BulbLengthRatio.Value, param.Min ?? 0m, param.Max ?? 0.2m);
                }
            }

            if (additional.BulbWidthRatio.HasValue)
            {
                var param = metadata.FirstOrDefault(m => m.ParameterIndex == 35); // Bbb
                if (param != null)
                {
                    vector[35] = Math.Clamp(additional.BulbWidthRatio.Value, param.Min ?? 0m, param.Max ?? 1m);
                }
            }

            if (additional.BulbHeightRatio.HasValue)
            {
                var param = metadata.FirstOrDefault(m => m.ParameterIndex == 34); // Hbb
                if (param != null)
                {
                    vector[34] = Math.Clamp(additional.BulbHeightRatio.Value, param.Min ?? 0m, param.Max ?? 1m);
                }
            }

            if (additional.BulbAsymmetryFactor.HasValue)
            {
                var param = metadata.FirstOrDefault(m => m.ParameterIndex == 36); // Lbbm
                if (param != null)
                {
                    vector[36] = Math.Clamp(additional.BulbAsymmetryFactor.Value, param.Min ?? -1m, param.Max ?? 1m);
                }
            }

            if (additional.BulbFilletRadius.HasValue)
            {
                var param = metadata.FirstOrDefault(m => m.ParameterIndex == 37); // Rbb
                if (param != null)
                {
                    vector[37] = Math.Clamp(additional.BulbFilletRadius.Value, param.Min ?? 0.05m, param.Max ?? 0.33m);
                }
            }

            // Ensure bulb dimensions are set to sensible defaults if they're too small
            // This ensures effective bulb geometry when bulb is enabled
            EnsureSensibleBulbDimensions(vector, metadata);

            _logger.LogDebug("[SHIPD_ADAPTER] Applied bulb geometry for bulbous_bow");
        }
    }

    /// <summary>
    /// Applies family-specific defaults from taxonomy (e.g., bit_BB for bulbous_bow, Atrans for transom_stern).
    /// </summary>
    private void ApplyFamilyDefaults(
        decimal[] vector,
        Dictionary<string, object> familyDefaults,
        string region,
        string familyName,
        IReadOnlyList<ShipDParameterMetadataDto> metadata,
        List<string> warnings)
    {
        foreach (var kvp in familyDefaults)
        {
            try
            {
                var paramName = kvp.Key;
                var paramValue = ExtractDecimalValue(kvp.Value);

                if (!paramValue.HasValue)
                {
                    continue;
                }

                // Map parameter names to ShipD vector indices
                int? paramIndex = paramName.ToLowerInvariant() switch
                {
                    "bit_bb" => 31,      // Bulbous bow flag
                    "bit_sb" => 32,      // Skeg/stern bulb flag (if exists)
                    "atrans" => 22,      // Transom area ratio
                    "beta" => 8,         // Bow flare/rake angle
                    "beta_trans" => 27,  // Stern rake angle
                    "rc" => 9,           // Bow curvature
                    "rc_trans" => 29,    // Stern curvature
                    "rk" => 10,          // Bow knuckle
                    "rk_trans" => 30,    // Stern knuckle
                    "lbb" => 33,         // Bulb length ratio
                    "hbb" => 34,         // Bulb height ratio
                    "bbb" => 35,         // Bulb width ratio
                    "lbbm" => 36,        // Bulb asymmetry
                    "rbb" => 37,         // Bulb fillet radius
                    "cdrft" => 19,       // Deadrise angle
                    _ => null
                };

                if (paramIndex.HasValue)
                {
                    var param = metadata.FirstOrDefault(m => m.ParameterIndex == paramIndex.Value);
                    if (param != null && param.Min.HasValue && param.Max.HasValue)
                    {
                        // Normalize value if needed (some are already 0-1, others are physical units)
                        decimal normalizedValue;
                        if (param.Min.Value >= 0m && param.Max.Value <= 1m)
                        {
                            // Already normalized (0-1 range)
                            normalizedValue = Math.Clamp(paramValue.Value, 0m, 1m);
                        }
                        else
                        {
                            // Physical unit - normalize to 0-1
                            normalizedValue = NormalizeValue(paramValue.Value, param.Min, param.Max, param.Mean, param.StdDev);
                        }

                        // Only apply if vector slot is empty (0) to avoid overriding user values
                        if (vector[paramIndex.Value] == 0m)
                        {
                            vector[paramIndex.Value] = normalizedValue;
                            _logger.LogDebug("[SHIPD_ADAPTER] Applied {Region} family default {ParamName}={Value} (normalized: {Normalized}) to vector[{Index}]",
                                region, paramName, paramValue.Value, normalizedValue, paramIndex.Value);
                        }
                        else
                        {
                            _logger.LogDebug("[SHIPD_ADAPTER] Skipped {Region} family default {ParamName} (vector[{Index}] already set: {Value})",
                                region, paramName, paramIndex.Value, vector[paramIndex.Value]);
                        }
                    }
                    else
                    {
                        // No metadata - apply value as-is if it's a ratio (0-1) or boolean (0/1)
                        if (paramName.ToLowerInvariant().StartsWith("bit_") || paramName.ToLowerInvariant() == "atrans")
                        {
                            // Boolean or ratio parameter - use value as-is
                            if (vector[paramIndex.Value] == 0m)
                            {
                                vector[paramIndex.Value] = Math.Clamp(paramValue.Value, 0m, 1m);
                                _logger.LogDebug("[SHIPD_ADAPTER] Applied {Region} family default {ParamName}={Value} to vector[{Index}] (no metadata)",
                                    region, paramName, paramValue.Value, paramIndex.Value);
                            }
                        }
                    }
                }
                else
                {
                    _logger.LogDebug("[SHIPD_ADAPTER] Unknown family default parameter name: {ParamName} for {Region} family {Family}",
                        paramName, region, familyName);
                }
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "[SHIPD_ADAPTER] Failed to apply family default {Key} for {Region} family {Family}",
                    kvp.Key, region, familyName);
            }
        }
    }

