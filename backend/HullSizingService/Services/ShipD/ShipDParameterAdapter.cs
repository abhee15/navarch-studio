    /// <summary>
    /// Safely extracts a decimal value from a JSON deserialized object (handles JsonElement, numeric types, etc.)
    /// </summary>
    private decimal? ExtractDecimalValue(object? value)
    {
        if (value == null)
        {
            return null;
        }

        try
        {
            // Handle JsonElement (common when deserializing JSON to Dictionary<string, object>)
            if (value is JsonElement jsonElement)
            {
                try
                {
                    if (jsonElement.ValueKind == JsonValueKind.Number)
                    {
                        return jsonElement.GetDecimal();
                    }
                    else if (jsonElement.ValueKind == JsonValueKind.String)
                    {
                        var str = jsonElement.GetString();
                        if (!string.IsNullOrEmpty(str) && decimal.TryParse(str, out var parsed))
                        {
                            return parsed;
                        }
                    }
                    else if (jsonElement.ValueKind == JsonValueKind.True)
                    {
                        return 1m;
                    }
                    else if (jsonElement.ValueKind == JsonValueKind.False)
                    {
                        return 0m;
                    }
                    // Try to get decimal regardless of ValueKind (handles edge cases)
                    try
                    {
                        return jsonElement.GetDecimal();
                    }
                    catch
                    {
                        // If GetDecimal() fails, try parsing as string
                        var str = jsonElement.GetRawText().Trim('"');
                        if (decimal.TryParse(str, out var parsed))
                        {
                            return parsed;
                        }
                    }
                }
                catch (Exception ex)
                {
                    _logger.LogWarning(ex, "[SHIPD_ADAPTER] Failed to extract decimal from JsonElement with ValueKind={ValueKind}", jsonElement.ValueKind);
                }
                return null;
            }

            // Handle direct numeric types
            if (value is decimal dec)
            {
                return dec;
            }
            if (value is double dbl)
            {
                return (decimal)dbl;
            }
            if (value is float flt)
            {
                return (decimal)flt;
            }
            if (value is int intVal)
            {
                return (decimal)intVal;
            }
            if (value is long longVal)
            {
                return (decimal)longVal;
            }

            // Try Convert.ToDecimal as fallback
            return Convert.ToDecimal(value);
        }
        catch (Exception)
        {
            // If all conversion attempts fail, return null
            return null;
        }
    }

    /// <summary>
    /// Normalizes a physical value to ShipD's 0-1 range using min/max bounds.
    /// </summary>
    private decimal NormalizeValue(decimal physicalValue, decimal? min, decimal? max, decimal? mean, decimal? stdDev)
    {
        if (!min.HasValue || !max.HasValue || min.Value >= max.Value)
        {
            // Fallback: use mean and stdDev if available
            if (mean.HasValue && stdDev.HasValue && stdDev.Value > 0)
            {
                var normalizedValue = (physicalValue - mean.Value) / (3 * stdDev.Value) + 0.5m;
                return Math.Clamp(normalizedValue, 0m, 1m);
            }
            return 0.5m; // Default to middle
        }

        // Linear normalization: (value - min) / (max - min)
        var normalizedResult = (physicalValue - min.Value) / (max.Value - min.Value);
        return Math.Clamp(normalizedResult, 0m, 1m);
    }

    /// <summary>
    /// Adjusts ShipD vector when principal dimensions change to maintain hull form character.
    /// Uses intelligent scaling to preserve design intent while applying new dimensions.
    /// </summary>
    public decimal[] AdjustVectorForDimensionChange(
        decimal[] originalVector,
        decimal oldLpp,
        decimal newLpp,
        decimal oldBeam,
        decimal newBeam,
        decimal oldDraft,
        decimal newDraft,
        IReadOnlyList<ShipDParameterMetadataDto> metadata)
    {
        var adjusted = (decimal[])originalVector.Clone();

        // Scale longitudinal proportions to maintain absolute lengths
        var lengthRatio = newLpp / oldLpp;
        if (Math.Abs(lengthRatio - 1.0m) > 0.05m)
        {
            // Adjust Lb, Ls to maintain absolute bow/stern lengths
            adjusted[1] = Math.Clamp(adjusted[1] * oldLpp / newLpp, 0.05m, 0.45m); // Lb
            adjusted[2] = Math.Clamp(adjusted[2] * oldLpp / newLpp, 0.05m, 0.45m); // Ls

            _logger.LogDebug(
                "[SHIPD_ADAPTER] Scaled longitudinal proportions for length change {Old}m → {New}m: Lb={Lb}, Ls={Ls}",
                oldLpp, newLpp, adjusted[1], adjusted[2]);
        }

        // Scale beam-related angles to maintain form
        var beamRatio = newBeam / oldBeam;
        if (Math.Abs(beamRatio - 1.0m) > 0.05m)
        {
            // Reduce flare angles if beam increases (maintain hull character)
            var beamScaleFactor = (decimal)Math.Pow((double)(oldBeam / newBeam), 0.5);
            adjusted[8] *= beamScaleFactor;  // Beta (bow flare)
            adjusted[27] *= beamScaleFactor; // Beta_trans (stern rake)

            _logger.LogDebug(
                "[SHIPD_ADAPTER] Scaled beam-related angles for beam change {Old}m → {New}m: Beta={Beta}, Beta_trans={BetaTrans}",
                oldBeam, newBeam, adjusted[8], adjusted[27]);
        }

        // Scale draft-related parameters
        var draftRatio = newDraft / oldDraft;
        if (Math.Abs(draftRatio - 1.0m) > 0.05m)
        {
            // Adjust deadrise to maintain form
            adjusted[19] *= (decimal)Math.Pow((double)(oldDraft / newDraft), 0.3); // Cdrft (deadrise)

            _logger.LogDebug(
                "[SHIPD_ADAPTER] Scaled draft-related parameters for draft change {Old}m → {New}m: Cdrft={Cdrft}",
                oldDraft, newDraft, adjusted[19]);
        }

        // Clamp all values to valid metadata ranges
        for (int i = 0; i < adjusted.Length; i++)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == i);
            if (param != null)
            {
                if (param.Min.HasValue) adjusted[i] = Math.Max(param.Min.Value, adjusted[i]);
                if (param.Max.HasValue) adjusted[i] = Math.Min(param.Max.Value, adjusted[i]);
            }
        }

        return adjusted;
    }

    /// <summary>
    /// Adjusts ShipD vector when form coefficients change.
    /// Modifies hull form parameters to achieve the target coefficient while maintaining design character.
    /// </summary>
    public decimal[] AdjustVectorForCoefficientChange(
        decimal[] originalVector,
        string coefficient,
        decimal oldValue,
        decimal newValue,
        IReadOnlyList<ShipDParameterMetadataDto> metadata)
    {
        var adjusted = (decimal[])originalVector.Clone();
        var ratio = newValue / oldValue;

        if (coefficient == "Cb")
        {
            // Adjust section fullness parameters
            // Higher Cb = fuller sections
            adjusted[9] *= ratio;   // Rc (bow curvature)
            adjusted[29] *= ratio;  // Rc_trans (stern curvature)

            // For significant Cb increases, also adjust midship features
            if (ratio > 1.05m)
            {
                // Increase fullness: enhance sheer, reduce tumblehome
                adjusted[20] = Math.Min(1.0m, adjusted[20] * 1.1m); // bit_EP_S (sheer)
                adjusted[21] = Math.Max(0.0m, adjusted[21] * 0.9m); // bit_EP_T (tumblehome)
            }

            _logger.LogDebug(
                "[SHIPD_ADAPTER] Adjusted Cb {Old} → {New}: Rc={Rc}, Rc_trans={RcTrans}",
                oldValue, newValue, adjusted[9], adjusted[29]);
        }
        else if (coefficient == "Cp")
        {
            // Adjust longitudinal distribution
            // Higher Cp = more parallel body (shorter bow/stern)
            var lmAdjust = (ratio - 1.0m) * 0.2m;
            adjusted[1] = Math.Max(0.05m, adjusted[1] - lmAdjust / 2); // Reduce Lb
            adjusted[2] = Math.Max(0.05m, adjusted[2] - lmAdjust / 2); // Reduce Ls

            _logger.LogDebug(
                "[SHIPD_ADAPTER] Adjusted Cp {Old} → {New}: Lb={Lb}, Ls={Ls}",
                oldValue, newValue, adjusted[1], adjusted[2]);
        }
        else if (coefficient == "Cwp")
        {
            // Adjust waterplane shape
            // Higher Cwp = wider waterplane at ends
            adjusted[8] *= ratio;   // Beta (flare)
            adjusted[27] *= ratio;  // Beta_trans (stern rake)

            _logger.LogDebug(
                "[SHIPD_ADAPTER] Adjusted Cwp {Old} → {New}: Beta={Beta}, Beta_trans={BetaTrans}",
                oldValue, newValue, adjusted[8], adjusted[27]);
        }

        // Validate Lb + Ls < 1.0
        if (adjusted[1] + adjusted[2] >= 1.0m)
        {
            var excess = adjusted[1] + adjusted[2] - 0.95m;
            adjusted[1] = Math.Max(0.05m, adjusted[1] - excess / 2);
            adjusted[2] = Math.Max(0.05m, adjusted[2] - excess / 2);
            _logger.LogWarning(
                "[SHIPD_ADAPTER] Clamped Lb+Ls to ensure Lm > 0: Lb={Lb}, Ls={Ls}",
                adjusted[1], adjusted[2]);
        }

        // Clamp all values to valid metadata ranges
        for (int i = 0; i < adjusted.Length; i++)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == i);
            if (param != null)
            {
                if (param.Min.HasValue) adjusted[i] = Math.Max(param.Min.Value, adjusted[i]);
                if (param.Max.HasValue) adjusted[i] = Math.Min(param.Max.Value, adjusted[i]);
            }
        }

        return adjusted;
    }

    /// <summary>
    /// Updates a single ShipD parameter in the vector (for direct parameter adjustments).
    /// Normalizes incoming denormalized values (e.g., degrees for angles) to 0-1 range.
    /// Ratio parameters are already in 0-1 range and used as-is.
    /// </summary>
    public decimal[] UpdateShipDParameter(
        decimal[] originalVector,
        int parameterIndex,
        decimal newValue,
        IReadOnlyList<ShipDParameterMetadataDto> metadata)
    {
        var adjusted = (decimal[])originalVector.Clone();

        if (parameterIndex < 0 || parameterIndex >= adjusted.Length)
        {
            throw new ArgumentOutOfRangeException(nameof(parameterIndex), $"Parameter index must be between 0 and {adjusted.Length - 1}");
        }

        var param = metadata.FirstOrDefault(m => m.ParameterIndex == parameterIndex);
        decimal normalizedValue = newValue;

        // Parameters that are ratios (0-1 range) - use value as-is
        var ratioParameters = new HashSet<int> { 1, 2, 9, 10, 14, 22, 24, 28, 29, 30, 33, 34, 35, 36, 37 };
        // Boolean parameters (0 or 1)
        var booleanParameters = new HashSet<int> { 20, 21, 31 };

        if (ratioParameters.Contains(parameterIndex))
        {
            // Ratio parameters are already in 0-1 range - use as-is
            normalizedValue = newValue;
            _logger.LogDebug(
                "[SHIPD_ADAPTER] Using ratio parameter[{Index}] value as-is: {Value}",
                parameterIndex, normalizedValue);
        }
        else if (booleanParameters.Contains(parameterIndex))
        {
            // Boolean parameters: convert to 0 or 1
            normalizedValue = newValue > 0.5m ? 1m : 0m;
            _logger.LogDebug(
                "[SHIPD_ADAPTER] Converted boolean parameter[{Index}]: {Value} -> {Normalized}",
                parameterIndex, newValue, normalizedValue);
        }
        else if (param != null && param.Min.HasValue && param.Max.HasValue)
        {
            // Physical parameters (angles, etc.) - normalize from physical units to 0-1 range
            var range = param.Max.Value - param.Min.Value;

            // Check if this is a physical parameter (min < 0 or max > 1) or value is outside [0, 1]
            bool isPhysicalParameter = param.Min.Value < 0m || param.Max.Value > 1m;
            bool valueOutsideNormalizedRange = newValue < 0m || newValue > 1m;

            if (range > 0m && (isPhysicalParameter || valueOutsideNormalizedRange))
            {
                // Value is denormalized (e.g., 15 degrees) - normalize it to 0-1 range
                normalizedValue = (newValue - param.Min.Value) / range;
                normalizedValue = Math.Max(0m, Math.Min(1m, normalizedValue)); // Clamp to [0, 1]
                _logger.LogDebug(
                    "[SHIPD_ADAPTER] Normalized physical parameter[{Index}]: {Value} ({Unit}) -> {Normalized} (0-1 range) using range [{Min}, {Max}]",
                    parameterIndex, newValue, param.Unit ?? "unit", normalizedValue, param.Min.Value, param.Max.Value);
            }
            else
            {
                // Value appears to already be normalized (0-1 range) or metadata suggests normalized
                normalizedValue = Math.Max(0m, Math.Min(1m, newValue));
                _logger.LogDebug(
                    "[SHIPD_ADAPTER] Parameter[{Index}] value appears normalized, using as-is: {Value}",
                    parameterIndex, normalizedValue);
            }
        }
        else
        {
            // No metadata available - assume value is already normalized (0-1 range)
            normalizedValue = Math.Max(0m, Math.Min(1m, newValue));
            _logger.LogWarning(
                "[SHIPD_ADAPTER] No metadata for parameter[{Index}], assuming normalized value: {Value}",
                parameterIndex, normalizedValue);
        }

        // Apply normalized value
        adjusted[parameterIndex] = normalizedValue;

        // Clamp to valid range (should already be in range, but double-check)
        if (param != null)
        {
            if (param.Min.HasValue) adjusted[parameterIndex] = Math.Max(0m, adjusted[parameterIndex]); // ShipD vector uses 0-1 range
            if (param.Max.HasValue) adjusted[parameterIndex] = Math.Min(1m, adjusted[parameterIndex]); // ShipD vector uses 0-1 range
        }

        // Special validation for longitudinal proportions (Lb + Ls < 1.0)
        if (parameterIndex == 1 || parameterIndex == 2) // Lb or Ls
        {
            if (adjusted[1] + adjusted[2] >= 1.0m)
            {
                var excess = adjusted[1] + adjusted[2] - 0.95m;
                if (parameterIndex == 1) // Adjusting Lb
                {
                    adjusted[1] = Math.Max(0.05m, adjusted[1] - excess);
                }
                else // Adjusting Ls
                {
                    adjusted[2] = Math.Max(0.05m, adjusted[2] - excess);
                }
                _logger.LogWarning(
                    "[SHIPD_ADAPTER] Clamped parameter {Index} to ensure Lb+Ls < 1.0: Lb={Lb}, Ls={Ls}",
                    parameterIndex, adjusted[1], adjusted[2]);
            }
        }

        _logger.LogDebug(
            "[SHIPD_ADAPTER] Updated ShipD parameter[{Index}] = {Value}",
            parameterIndex, adjusted[parameterIndex]);

        return adjusted;
    }

    /// <summary>
    /// Ensures bulb dimensions (Lbb, Hbb, Bbb) are set to sensible defaults when bulb is enabled.
    /// This prevents the issue where bulb is enabled but dimensions are zero or minimal, resulting in no effective bulb geometry.
    /// </summary>
    /// <param name="vector">ShipD parameter vector</param>
    /// <param name="metadata">Parameter metadata</param>
    private void EnsureSensibleBulbDimensions(
        decimal[] vector,
        IReadOnlyList<ShipDParameterMetadataDto> metadata)
    {
        // Only apply if bulb is enabled
        if (vector[31] <= 0.5m) // bit_BB
        {
            return;
        }

        const decimal minLbbThreshold = 0.01m; // 1% of Lpp (very small, should be at least 15%)
        const decimal minHbbThreshold = 0.05m; // 5% of draft (very small, should be at least 20%)
        const decimal minBbbThreshold = 0.05m; // 5% of beam (very small, should be at least 20%)

        // Sensible defaults based on recommendations:
        // - Lbb: 15% of Lpp (normalized: 0.15)
        // - Hbb: 20% of draft (normalized: 0.2)
        // - Bbb: 25% of beam (normalized: 0.25)
        const decimal defaultLbb = 0.15m; // 15% of Lpp
        const decimal defaultHbb = 0.2m;  // 20% of draft
        const decimal defaultBbb = 0.25m; // 25% of beam

        bool updated = false;

        // Check and set Lbb (Bulb length ratio, index 33)
        if (vector[33] < minLbbThreshold)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == 33);
            if (param != null)
            {
                var oldValue = vector[33];
                var clampedValue = Math.Clamp(defaultLbb, param.Min ?? 0m, param.Max ?? 0.2m);
                if (oldValue != clampedValue)
                {
                    vector[33] = clampedValue;
                    updated = true;
                    _logger.LogInformation(
                        "[SHIPD_ADAPTER] Set Lbb to sensible default: {Value} (was {OldValue}, recommended: 15% of Lpp)",
                        clampedValue, oldValue);
                }
            }
        }

        // Check and set Hbb (Bulb height ratio, index 34)
        if (vector[34] < minHbbThreshold)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == 34);
            if (param != null)
            {
                var oldValue = vector[34];
                var clampedValue = Math.Clamp(defaultHbb, param.Min ?? 0m, param.Max ?? 1m);
                if (oldValue != clampedValue)
                {
                    vector[34] = clampedValue;
                    updated = true;
                    _logger.LogInformation(
                        "[SHIPD_ADAPTER] Set Hbb to sensible default: {Value} (was {OldValue}, recommended: 20% of draft)",
                        clampedValue, oldValue);
                }
            }
        }

        // Check and set Bbb (Bulb width ratio, index 35)
        if (vector[35] < minBbbThreshold)
        {
            var param = metadata.FirstOrDefault(m => m.ParameterIndex == 35);
            if (param != null)
            {
                var oldValue = vector[35];
                var clampedValue = Math.Clamp(defaultBbb, param.Min ?? 0m, param.Max ?? 1m);
                if (oldValue != clampedValue)
                {
                    vector[35] = clampedValue;
                    updated = true;
                    _logger.LogInformation(
                        "[SHIPD_ADAPTER] Set Bbb to sensible default: {Value} (was {OldValue}, recommended: 25% of beam)",
                        clampedValue, oldValue);
                }
            }
        }

        if (updated)
        {
            _logger.LogWarning(
                "[SHIPD_ADAPTER] ✅ Applied sensible bulb dimension defaults: Lbb={Lbb}, Hbb={Hbb}, Bbb={Bbb}",
                vector[33], vector[34], vector[35]);
        }
    }

